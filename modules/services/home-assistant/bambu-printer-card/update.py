# Lines whose colours are filament or demo data, not styling.
DATA_LINE = re.compile(
    r"(dataset\.color|attr\.color|isEmpty \?|slot\.color ===|type: '|id: i \+ 1)"
)
RGBA = re.compile(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)")
HEXCOLOUR = re.compile(r"#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b")


def alpha(colour: str, a: str | None) -> str:
    if a is None or float(a) == 1:
        return colour
    return f"color-mix(in srgb, {colour} {round(float(a) * 100, 1):g}%, transparent)"


def recolour_line(line: str, unmapped: set[str]) -> str:
    def rgba(m: re.Match[str]) -> str:
        rgb = (int(m[1]), int(m[2]), int(m[3]))
        if rgb == (255, 255, 255):
            return alpha("var(--bpc-fg)", m[4])
        if rgb == (0, 0, 0):
            return m[0] if "shadow" in line else alpha("var(--bpc-bg)", m[4])
        if rgb in RGB:
            return alpha(f"var(--bpc-{RGB[rgb]})", m[4])
        unmapped.add(m[0])
        return m[0]

    def hexcolour(m: re.Match[str]) -> str:
        h = m[1].lower()
        if h in HEX:
            return f"var(--bpc-{HEX[h]})"
        if h not in KEEP_HEX:
            unmapped.add(m[0])
        return m[0]

    line = RGBA.sub(rgba, line)
    line = HEXCOLOUR.sub(hexcolour, line)
    line = re.sub(r"(\bcolor:\s*)white\b", r"\1var(--bpc-fg)", line)
    return line.replace(
        "font-family: system-ui, -apple-system, sans-serif;", "font-family: var(--bpc-font);"
    )


def recolour(src: str) -> str:
    unmapped: set[str] = set()
    lines = [
        line
        if DATA_LINE.search(line) or line.lstrip().startswith(("//", "*", "/*"))
        else recolour_line(line, unmapped)
        for line in src.split("\n")
    ]
    if unmapped:
        raise SystemExit(f"unmapped colours, add them to RGB or HEX: {sorted(unmapped)}")
    return "\n".join(lines)


def replace_once(src: str, old: str, new: str) -> str:
    if old not in src:
        raise SystemExit(f"upstream changed, anchor not found:\n{old}")
    return src.replace(old, new, 1)


def strip_calls(src: str, fn: str) -> str:
    out, i = [], 0
    while (j := src.find(fn + "(", i)) >= 0:
        out.append(src[i:j])
        k, depth = j + len(fn), 0
        while True:
            depth += {"(": 1, ")": -1}.get(src[k], 0)
            if depth == 0 and src[k] == ")":
                break
            k += 1
        i = k + 1
    out.append(src[i:])
    return "".join(out)


def unless_templated(name: str) -> Callable[[re.Match[str]], str]:
    return lambda m: m[0] if "${" in m[0] else name


def flatten(src: str) -> str:
    src = re.sub(r"box-shadow\s*:[^;{}]*;", unless_templated("box-shadow: none;"), src)
    src = re.sub(r"text-shadow\s*:[^;{}]*;", unless_templated("text-shadow: none;"), src)
    src = re.sub(r"(?:-webkit-)?backdrop-filter\s*:[^;{}]*;", unless_templated(""), src)
    src = strip_calls(src, "drop-shadow")
    src = re.sub(r"filter:\s*;", "filter: none;", src)
    src = src.replace(
        "linear-gradient(145deg, var(--bpc-surface-deep), var(--bpc-surface-lo))",
        "var(--bpc-surface-pressed)",
    )
    src = re.sub(
        r"linear-gradient\(145deg, var\(--bpc-surface-(?:hi|lo)\), "
        r"var\(--bpc-surface-(?:hi|lo)\)\)",
        "var(--bpc-surface)",
        src,
    )
    src = src.replace("linear-gradient(to right, var(--bpc-ok), var(--bpc-ok))", "var(--bpc-ok)")
    src = src.replace("linear-gradient(90deg, var(--bpc-ok), var(--bpc-ok))", "var(--bpc-ok)")
    render = src.index("this.shadowRoot.innerHTML = `")
    end = src.index("</style>", render)
    return src[:end] + FLAT_CSS + "      " + src[end:]


