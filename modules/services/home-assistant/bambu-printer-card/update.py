def build(src: str) -> str:
    src = recolour(src)
    for old, new in FIXES:
        src = replace_once(src, old, new)
    src = src.replace("/local/community/Prism-Dashboard/images/printer-blank.jpg", IMAGE)
    src = src.replace("type: 'prism-bambu'", "type: 'bambu-printer-card'")
    src = src.replace(
        "<style>", "<style>\n        :host, #prism-camera-popup-overlay {" + PALETTE + "        }"
    )
    return HEADER + flatten(src)


def main() -> None:
    with urllib.request.urlopen(SOURCE) as response:
        upstream = response.read().decode()
    OUT.write_text(build(upstream))


if __name__ == "__main__":
    main()
